/**
 * Creates a user-owned onboarding path from a snapshot of a fully authored blueprint path.
 *
 * The conversion copies content and graph layout into a new aggregate. Dependency
 * edges are rebuilt against the copied entities, keeping blueprint and onboarding
 * persistence ownership separate. Content generated by the AI service for
 * `AI_ENHANCED` phases (keyed by blueprint phase id) is merged in on top of the
 * authored content, so a prompt-only phase is filled with the assembled steps
 * and knowledge check while an [OnboardingPathFromBlueprintFactory] path keeps
 * the blueprint itself untouched.
 */
@Component
class OnboardingPathFromBlueprintFactory {
    /**
     * Deep-copies [blueprint] for [userId].
     *
     * @param blueprint The source blueprint whose complete graph is copied.
     * @param userId The user who owns the resulting onboarding path.
     * @param generatedContentByBlueprintPhaseId AI-assembled content for `AI_ENHANCED` phases,
     *   keyed by source blueprint phase id.
     * @return A new, unsaved onboarding path aggregate.
     */
    fun createFrom(
        blueprint: BlueprintSnapshot,
        userId: UUID,
        projectRoleIds: Set<UUID> = emptySet(),
        skillIds: Set<UUID> = emptySet(),
        generatedContentByBlueprintPhaseId: Map<UUID, GeneratedPhaseContent> = emptyMap(),
        generationStatusByBlueprintPhaseId: Map<UUID, GenerationStatus> = emptyMap(),
    ): OnboardingPath {
        val onboardingPath = OnboardingPath(
            userId = userId,
            blueprintId = blueprint.id,
        )
        val phasesByBlueprintId = mutableMapOf<UUID, OnboardingPhase>()
        val nodesByBlueprintId = mutableMapOf<UUID, OnboardingSubGraphNode>()
        val includedPhases = blueprint.phases.filter { phase ->
            phase.isIncludedFor(projectRoleIds, skillIds)
        }

        includedPhases
            .sortedBy { it.position }
            .map {
                it.copyTo(
                    onboardingPath = onboardingPath,
                    nodesByBlueprintId = nodesByBlueprintId,
                    generated = generatedContentByBlueprintPhaseId[it.id],
                    generationStatus = generationStatusByBlueprintPhaseId[it.id],
                )
            }.forEach { copied ->
                onboardingPath.phases += copied.entity
                phasesByBlueprintId[copied.sourceBlueprintId] = copied.entity
            }

        wirePhaseBlockers(includedPhases, phasesByBlueprintId)

        val nodeEdges = includedPhases.flatMap { phase ->
            phase.steps.map { it.id to it.blockedBy } + phase.checkQuestions.map { it.id to it.blockedBy }
        }
        for ((nodeId, blockerIds) in nodeEdges) {
            blockerIds.mapNotNull(nodesByBlueprintId::get).forEach(nodesByBlueprintId.getValue(nodeId).blockedBy::add)
        }

        return onboardingPath
    }

    private fun BlueprintPhaseSnapshot.copyTo(
        onboardingPath: OnboardingPath,
        nodesByBlueprintId: MutableMap<UUID, OnboardingSubGraphNode>,
        generated: GeneratedPhaseContent? = null,
        generationStatus: GenerationStatus? = null,
    ): CopiedPhase {
        val resolvedGenerationStatus = generationStatus ?: when {
            type != BlueprintPhaseType.AI_ENHANCED -> GenerationStatus.NOT_APPLICABLE
            generated == null || generated.isEmpty() -> GenerationStatus.EMPTY
            else -> GenerationStatus.GENERATED
        }
        val onboardingPhase = OnboardingPhase(
            path = onboardingPath,
            position = position,
            title = title,
            description = description.orEmpty(),
            generationStatus = resolvedGenerationStatus,
            graphX = graphX,
            graphY = graphY,
        )

        steps
            .sortedBy { it.position }
            .map { it.copyTo(onboardingPhase) }
            .forEach { copied ->
                onboardingPhase.steps += copied.entity
                nodesByBlueprintId[copied.sourceBlueprintId] = copied.entity
            }

        checkQuestions
            .sortedBy { it.position }
            .map { it.copyTo(onboardingPhase) }
            .forEach { copied ->
                onboardingPhase.checkQuestions += copied.entity
                nodesByBlueprintId[copied.sourceBlueprintId] = copied.entity
            }

        if (generated != null) {
            generated.copyInto(onboardingPhase)
        }

        return CopiedPhase(id, onboardingPhase)
    }

    private fun GeneratedPhaseContent.isEmpty(): Boolean = steps.isEmpty() && checkQuestions.isEmpty()

    private fun wirePhaseBlockers(
        includedPhases: List<BlueprintPhaseSnapshot>,
        phasesByBlueprintId: Map<UUID, OnboardingPhase>,
    ) {
        val byId = includedPhases.associateBy { it.id }

        fun visibleBlockers(
            blueprintPhase: BlueprintPhaseSnapshot,
            visiting: MutableSet<UUID>,
        ): Set<OnboardingPhase> {
            val copied = phasesByBlueprintId[blueprintPhase.id] ?: return emptySet()
            if (!copied.generationStatus.isHiddenFromUser()) return setOf(copied)
            if (!visiting.add(blueprintPhase.id)) return emptySet()
            val inherited = blueprintPhase.blockedBy
                .mapNotNull(byId::get)
                .flatMap { blocker -> visibleBlockers(blocker, visiting) }
                .toSet()
            visiting.remove(blueprintPhase.id)
            return inherited
        }

        includedPhases.forEach { blueprintPhase ->
            val onboardingPhase = phasesByBlueprintId.getValue(blueprintPhase.id)
            if (onboardingPhase.generationStatus.isHiddenFromUser()) {
                blueprintPhase.blockedBy
                    .mapNotNull { blockerId -> phasesByBlueprintId[blockerId] }
                    .forEach(onboardingPhase.blockedBy::add)
            } else {
                blueprintPhase.blockedBy
                    .mapNotNull(byId::get)
                    .flatMap { blocker -> visibleBlockers(blocker, mutableSetOf()) }
                    .forEach(onboardingPhase.blockedBy::add)
            }
        }
    }

    private fun GeneratedPhaseContent.copyInto(onboardingPhase: OnboardingPhase) {
        val nodesByKey = mutableMapOf<String, OnboardingSubGraphNode>()
        val nodes = mutableListOf<OnboardingSubGraphNode>()
        val nodeEdges = mutableListOf<List<String>>()

        var stepPosition = onboardingPhase.steps.maxOfOrNull { it.position }?.let { it + 1 } ?: 0
        for (step in steps) {
            val onboardingStep = OnboardingStep(
                phase = onboardingPhase,
                position = stepPosition,
                title = step.title,
                description = step.description,
                type = StepType.TASK,
                aiAssisted = true,
                estimatedMinutes = step.estimatedMinutes ?: 0,
                tasks = mutableListOf(),
                resources = mutableListOf(),
                expectedOutcome = step.expectedOutcome,
                status = StepStatus.WAITING,
            )
            step.tasks.forEachIndexed { index, task ->
                onboardingStep.tasks += OnboardingTask(
                    step = onboardingStep,
                    position = index,
                    title = task.title,
                    description = task.description,
                )
            }
            step.resources.forEach { resource ->
                onboardingStep.resources += OnboardingResource(
                    step = onboardingStep,
                    title = resource.title,
                    description = "",
                    url = resource.url,
                )
            }
            onboardingPhase.steps += onboardingStep
            registerNode(step.key, onboardingStep, nodesByKey, nodes, nodeEdges, step.blockedBy)
            stepPosition += 1
        }

        var questionPosition =
            onboardingPhase.checkQuestions.maxOfOrNull { it.position }?.let { it + 1 } ?: 0
        for (question in checkQuestions) {
            val onboardingQuestion = PhaseCheckQuestion(
                phase = onboardingPhase,
                position = questionPosition,
                type = question.type,
                question = question.question,
                explanation = question.explanation,
                correctAnswer = question.correctAnswer,
                options = mutableListOf(),
            )
            question.options.forEachIndexed { index, option ->
                onboardingQuestion.options += PhaseCheckOption(
                    question = onboardingQuestion,
                    position = index,
                    label = option.label,
                    correct = option.correct,
                )
            }
            onboardingPhase.checkQuestions += onboardingQuestion
            registerNode(question.key, onboardingQuestion, nodesByKey, nodes, nodeEdges, question.blockedBy)
            questionPosition += 1
        }

        // Edges are wired after every node exists so a reference may point at a
        // later item; a key that resolves to nothing or to the node itself is
        // dropped rather than left dangling.
        nodes.forEachIndexed { index, node ->
            for (blockerKey in nodeEdges[index]) {
                nodesByKey[blockerKey]?.let { blocker ->
                    if (blocker != node) {
                        node.blockedBy += blocker
                    }
                }
            }
        }
    }

    private fun registerNode(
        key: String,
        node: OnboardingSubGraphNode,
        nodesByKey: MutableMap<String, OnboardingSubGraphNode>,
        nodes: MutableList<OnboardingSubGraphNode>,
        nodeEdges: MutableList<List<String>>,
        blockedBy: List<String>,
    ) {
        nodes += node
        nodeEdges += blockedBy
        if (key.isNotBlank() && key !in nodesByKey) {
            nodesByKey[key] = node
        }
    }

    private fun BlueprintStepSnapshot.copyTo(onboardingPhase: OnboardingPhase): CopiedNode<OnboardingStep> {
        val onboardingStep = OnboardingStep(
            phase = onboardingPhase,
            position = position,
            title = title,
            description = description,
            type = type,
            aiAssisted = aiAssisted,
            estimatedMinutes = estimatedMinutes,
            expectedOutcome = expectedOutcome,
            status = StepStatus.WAITING,
            graphX = graphX,
            graphY = graphY,
        )

        tasks
            .sortedBy { it.position }
            .map { it.copyTo(onboardingStep) }
            .forEach(onboardingStep.tasks::add)
        resources
            .map { it.copyTo(onboardingStep) }
            .forEach(onboardingStep.resources::add)

        return CopiedNode(id, onboardingStep)
    }

    private fun BlueprintCheckQuestionSnapshot.copyTo(
        onboardingPhase: OnboardingPhase,
    ): CopiedNode<PhaseCheckQuestion> {
        val onboardingQuestion = PhaseCheckQuestion(
            phase = onboardingPhase,
            title = title,
            position = position,
            type = type,
            question = question,
            explanation = explanation,
            correctAnswer = correctAnswer,
            graphX = graphX,
            graphY = graphY,
        )

        options
            .sortedBy { it.position }
            .map { it.copyTo(onboardingQuestion) }
            .forEach(onboardingQuestion.options::add)

        return CopiedNode(id, onboardingQuestion)
    }

    private fun BlueprintTaskSnapshot.copyTo(onboardingStep: OnboardingStep): OnboardingTask {
        return OnboardingTask(
            step = onboardingStep,
            position = position,
            title = title,
            description = description,
        )
    }

    private fun BlueprintResourceSnapshot.copyTo(onboardingStep: OnboardingStep): OnboardingResource {
        return OnboardingResource(
            step = onboardingStep,
            title = title,
            description = description,
            url = url,
        )
    }

    private fun BlueprintCheckOptionSnapshot.copyTo(onboardingQuestion: PhaseCheckQuestion): PhaseCheckOption {
        return PhaseCheckOption(
            question = onboardingQuestion,
            position = position,
            label = label,
            correct = correct,
        )
    }

    private data class CopiedPhase(
        val sourceBlueprintId: UUID,
        val entity: OnboardingPhase,
    )

    private data class CopiedNode<T : OnboardingSubGraphNode>(
        val sourceBlueprintId: UUID,
        val entity: T,
    )
}
